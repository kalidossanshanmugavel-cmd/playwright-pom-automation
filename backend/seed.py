def seed_database(db: Session):
    # Idempotent seed: existing rows are reused, so --reload does not duplicate data.
    seed_users = [
        {"name": "Demo Student", "email": "student@example.com", "password": "Student@123", "role": "student"},
        {"name": "Demo Trainer", "email": "trainer@example.com", "password": "Trainer@123", "role": "trainer"},
        {"name": "Demo Admin", "email": "admin@example.com", "password": "Admin@123", "role": "admin"},
    ]

    for item in seed_users:
        user = db.query(User).filter(User.email == item["email"]).first()
        if not user:
            db.add(User(
                name=item["name"],
                email=item["email"],
                password_hash=hash_password(item["password"]),
                role=item["role"],
            ))
        else:
            # Keep existing demo users aligned with the RBAC test fixtures.
            user.role = item["role"]
    db.commit()

    for item in COURSES:
        course = db.query(Course).filter(Course.slug == item["slug"]).first()
        if course:
            continue

        course = Course(slug=item["slug"], title=item["title"],
                        description=item["description"], level=item["level"],
                        duration=item["duration"])
        db.add(course)
        db.flush()

        db.add_all([
            Lesson(course_id=course.id, title=x["title"], content=x["content"],
                   lesson_order=x["order"]) for x in item["lessons"]
        ])
        db.add_all([
            Question(course_id=course.id, question=x["question"],
                     option_a=x["a"], option_b=x["b"], option_c=x["c"],
                     option_d=x["d"], correct_answer=x["correct"])
            for x in item["mcqs"]
        ])
        db.add_all([
            PracticeQuestion(course_id=course.id, title=x["title"],
                             question=x["question"], difficulty=x["difficulty"])
            for x in item["practice"]
        ])
        db.commit()

    print("Database seed verified: users, courses, lessons, MCQs and practice content are ready.")
